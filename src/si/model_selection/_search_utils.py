import numpy as np
from data.dataset import Dataset


def k_fold_indices(n_samples, cv=5, seed=None):
    """Generate training and validation indices for k-fold cross-validation.

    The dataset indices are shuffled and then divided into k approximately equal-sized folds. 
    Each fold is used once as the validation set, 
    while the remaining folds are used as the training set.

    Parameters
    ----------
    n_samples : int
        Number of samples in the dataset.
    cv : int, default=5
        Number of folds to create.
    seed : int or None, default=None
        Random seed used to ensure reproducibility of the shuffle.

    Returns
    -------
    list of tuple of numpy.ndarray
        A list containing one pair of arrays per fold: (train_indices, val_indices).
    """
    rng = np.random.default_rng(seed)

    indices = rng.permutation(n_samples)
    folds = np.array_split(indices, cv)

    splits = []

    for i in range(cv):
        val_indices = folds[i]
        train_indices = np.concatenate(
            [folds[j] for j in range(cv) if j != i]
        )

        splits.append((train_indices, val_indices))

    return splits


def cross_validate_configuration(model, dataset, configuration, folds, scoring=None):
    """Evaluate a hyperparameter configuration using k-fold cross-validation.

    A new model is built and trained for each fold. The model is evaluated on the corresponding validation set, 
    and the mean validation score across all folds is returned.

    Parameters
    ----------
    model : callable
        Function or callable object that builds a new model when called with the hyperparameter configuration.
    dataset : Dataset
        Dataset containing the input features and target values.
    configuration : dict
        Dictionary containing the hyperparameter names and values used to build the model.
    folds : list of tuple of numpy.ndarray
        Training and validation indices generated by k_fold_indices.
    scoring : callable or None, default=None
        Scoring function used to evaluate predictions. If None, the model's score method is used.

    Returns
    -------
    float
        Mean validation score across all folds.
    """
    scores = []

    for train_indices, val_indices in folds:

        train_dataset = Dataset(
            dataset.X[train_indices],
            dataset.y[train_indices]
        )

        val_dataset = Dataset(
            dataset.X[val_indices],
            dataset.y[val_indices]
        )

        # Build a fresh model for each fold.
        current_model = model(**configuration)

        current_model.fit(train_dataset)

        if scoring is None:
            score = current_model.score(val_dataset)
        else:
            predictions = current_model.predict(val_dataset)
            y_true = val_dataset.y.reshape(-1, 1) if np.ndim(val_dataset.y) == 1 else val_dataset.y
            score = scoring(y_true, predictions)

        scores.append(score)

    return np.mean(scores)